import React, { useState } from 'react';
import { api } from '../services/api';

export default function AiPharmacist() {
    const [query, setQuery] = useState('');
    const [result, setResult] = useState(null);

    const ask = async (q) => {
        const text = q || query;
        if (!text.trim()) return;
        setQuery(text);
        try {
            const data = await api.consultAi(text);
            setResult(data);
        } catch (e) {
            alert('AI consultation service failed');
        }
    };

    return (
        <div className="space-y-6">
            <div className="glass-card p-8 relative overflow-hidden">
                <div className="flex flex-col md:flex-row items-start md:items-center justify-between gap-6 relative z-10">
                    <div>
                        <div className="inline-flex items-center gap-1.5 px-2.5 py-1 glass-well text-xs font-mono text-zinc-300 mb-3">
                            <i data-lucide="sparkles" className="w-3.5 h-3.5 text-emerald-400"></i>
                            <span>Clinical Heuristic Advisor</span>
                        </div>
                        <h2 className="text-2xl font-bold tracking-tight text-white">Pharmacological Interaction &amp; Symptom Intelligence</h2>
                        <p className="text-zinc-400 text-xs mt-1.5 max-w-xl leading-relaxed">
                            Consult the heuristic clinical engine for drug interaction checks, supplement stacking, dosage protocols, and contraindication notices.
                        </p>
                    </div>
                    <div className="w-14 h-14 rounded-2xl glass-well flex items-center justify-center shrink-0">
                        <i data-lucide="stethoscope" className="w-7 h-7 text-emerald-400"></i>
                    </div>
                </div>

                <div className="mt-6 flex flex-wrap gap-2">
                    <button onClick={() => ask('headache')} className="glass-btn-secondary text-xs py-1.5 px-3">Headache Relief</button>
                    <button onClick={() => ask('vitamin')} className="glass-btn-secondary text-xs py-1.5 px-3">Vitamin Stacking</button>
                    <button onClick={() => ask('antibiotic')} className="glass-btn-secondary text-xs py-1.5 px-3">Antibiotic Rules</button>
                    <button onClick={() => ask('sleep')} className="glass-btn-secondary text-xs py-1.5 px-3">Deep Sleep Optimization</button>
                    <button onClick={() => ask('energy')} className="glass-btn-secondary text-xs py-1.5 px-3">Sustained Clean Energy</button>
                </div>

                <div className="mt-5 flex gap-2">
                    <input
                        type="text"
                        placeholder="Query a medication symptom or pharmacological interaction..."
                        value={query}
                        onChange={(e) => setQuery(e.target.value)}
                        onKeyDown={(e) => e.key === 'Enter' && ask()}
                        className="glass-input w-full px-4 py-3 text-sm"
                    />
                    <button onClick={() => ask()} className="glass-btn-primary px-6 py-3 text-xs font-semibold whitespace-nowrap">
                        <span>Consult Engine</span>
                    </button>
                </div>
            </div>

            {result && (
                <div className="glass-card p-6 space-y-4">
                    <div className="flex items-center gap-3">
                        <span className="text-2xl font-mono text-emerald-400">{result.moodEmoji || '✦'}</span>
                        <div>
                            <h3 className="font-bold text-white text-sm">{result.title}</h3>
                            <p className="text-xs text-zinc-400">Generated by pharma.Co Clinical Heuristic Engine</p>
                        </div>
                    </div>
                    <div className="glass-well p-4 text-xs text-zinc-200 leading-relaxed font-sans">
                        {result.advice}
                    </div>
                    <div className="flex items-center gap-2.5 text-xs text-amber-300 glass-well p-3 border border-amber-500/20">
                        <i data-lucide="alert-triangle" className="w-4 h-4 shrink-0 text-amber-400"></i>
                        <span>{result.warning}</span>
                    </div>
                </div>
            )}
        </div>
    );
}
